import assert from 'node:assert/strict';
import {prepareR43SelectiveAnalyticsCall,classifyR43CallerEvidence,R43_PATHS} from './r43-analytics-live-carrier-binding.mjs';
import {SOURCE_BLOBS} from './r42-analytics-caller-compat.mjs';
const head='6337840188b0f2b15ef070f9872f65b0ae2bba53';
const blobs=Object.fromEntries(Object.entries(R43_PATHS).map(([k,p])=>[p,SOURCE_BLOBS[k]]));
const receipt=Object.entries(R43_PATHS).map(([k,path])=>({path,blob_sha:SOURCE_BLOBS[k],current_head:head,complete:true,readback_type:'GITHUB_FETCH_FILE',fetch_ref:'GitHub fresh read '+path}));
const req={CALLER_FACET:'SPEECH_DESIGN',TASK:'Source analysis',REQUIRED_CAPABILITIES:['SOURCE_CLASSIFICATION','FRESHNESS_CHECK'],CONTEXT:{},EVIDENCE_SCOPE:'SOURCE',FRESHNESS_REQUIREMENT:'CURRENT',EXPECTED_RESULT:'EVIDENCE',RETURN_TARGET:'SPEECH_DESIGN'};
const args={currentHead:head,freshProductiveBlobs:blobs,sourceReadbacks:receipt};
let n=0;
const pass=(name,predicate)=>{assert.ok(predicate(),name);n++};
const reject=(name,opts)=>{assert.throws(()=>prepareR43SelectiveAnalyticsCall(req,opts),undefined,name);n++};
const view=prepareR43SelectiveAnalyticsCall(req,args);
pass('source bound',()=>view.sourceReadbackCount===3&&view.verifiedSourceHead===head);
pass('no host pass',()=>!view.productivePluginHost&&view.hostAcceptanceGatesClosed===0&&view.stillOpenHostGates===18);
pass('speaker return',()=>view.returnFacet==='SPEECH_DESIGN');
reject('no source records',{...args,sourceReadbacks:[]});
reject('stale head',{...args,currentHead:'f'.repeat(40)});
reject('missing actual current hash',{...args,freshProductiveBlobs:{}});
reject('hash superseded',{...args,freshProductiveBlobs:{...blobs,[R43_PATHS.speechContract]:'f'.repeat(40)}});
reject('duplicate receipts',{...args,sourceReadbacks:[...receipt,receipt[0]]});
reject('forged receipt',{...args,sourceReadbacks:receipt.map((x,i)=>i===0?{...x,blob_sha:'0'.repeat(40)}:x)});
reject('incomplete receipt',{...args,sourceReadbacks:receipt.map((x,i)=>i===0?{...x,complete:false}:x)});
reject('no readback type',{...args,sourceReadbacks:receipt.map((x,i)=>i===0?{...x,readback_type:'SEARCH_RESULT'}:x)});
reject('no fetch reference',{...args,sourceReadbacks:receipt.map((x,i)=>i===0?{...x,fetch_ref:null}:x)});
pass('speaker classification',()=>classifyR43CallerEvidence({caller:'SPEECH_DESIGN',explicitContract:true,capabilityBundle:true}).permittedLiveInvocation);
pass('studio not auto enabled',()=>!classifyR43CallerEvidence({caller:'STUDIO2',capabilityBundle:true}).permittedLiveInvocation);
pass('track not auto enabled',()=>classifyR43CallerEvidence({caller:'TRACK_DESIGN',explicitContract:false,capabilityBundle:false}).status==='COVERAGE_PENDING');
assert.throws(()=>prepareR43SelectiveAnalyticsCall({...req,CALLER_FACET:'STUDIO2',RETURN_TARGET:'STUDIO2'},args));n++;
console.log(JSON.stringify({status:'PASS',checks:n,scope:'SOURCE_INTEGRATION_ONLY',host:false,gitBlob:'7aaa027e53862d16b0b768d212c476eba4600ec7'}));
