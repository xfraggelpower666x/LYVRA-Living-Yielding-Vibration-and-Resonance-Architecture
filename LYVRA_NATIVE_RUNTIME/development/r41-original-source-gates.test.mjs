// R41 regression test: exact native development source, no paid host, no writes.
// Run: node LYVRA_NATIVE_RUNTIME/development/r41-original-source-gates.test.mjs
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
import {ingestSunoMonitorResult,SUNO_TASK_ID} from './r40-suno-source-bridge.mjs';
import {assessAnalyticsMigration} from './r40-analytics-parentage-guard.mjs';
import {ingestAnalyticsEvidence} from './r39-r26-functional-extracts.mjs';
import {correct,defaultState} from './r38_original_r26/dictation.mjs';
const here=dirname(fileURLToPath(import.meta.url));
const ledger=JSON.parse(readFileSync(join(here,'r41-analytics-original-carrier-readbacks.json'),'utf8'));
let n=0;const ck=(predicate,claim)=>{assert.ok(predicate,claim);n++};
const H=ledger.current_head,P=ledger.current_pointer_blob;
const time='2026-11-05T05:00:00Z';
const task={taskId:SUNO_TASK_ID,enabled:true,lastRunTime:time};
const result={run_id:'LOCAL_R41_FIXTURE_NOT_PROVIDER',recorded_status:'completed',completed_at:time,content_text:'https://suno.com/release-notes/suno-mcp-beta local test only',content_truncated:false,is_failure_message:false};
const body='Original source fixture, not a fetched Suno page';
const sha=createHash('sha256').update(body).digest('hex');
const proof={url:'https://suno.com/release-notes/suno-mcp-beta',class:'OFFICIAL_SUNO',readback:true,revision:'R41_TEST',accessedAt:time,content_text:body,content_sha256:sha,content_truncated:false,retrieval_ref:'LOCAL_FIXTURE_NOT_HOST'};
const ingest=(x)=>ingestSunoMonitorResult({...task,result,currentHead:H,sourceRevision:H,reviewedSources:[{...proof,...x}]});
ck(ingestSunoMonitorResult(task).status==='RUN_METADATA_ONLY','task metadata not source');
ck(!ingest({readback:false}).accepted,'readback flag false');
ck(!ingest({content_text:undefined}).accepted,'missing original source bytes');
ck(!ingest({content_sha256:'0'.repeat(64)}).accepted,'wrong original source checksum');
ck(!ingest({retrieval_ref:null}).accepted,'missing source retrieval reference');
ck(!ingest({content_truncated:true}).accepted,'truncated source');
ck(!ingest({accessedAt:'invalid'}).accepted,'invalid accessedAt');
ck(!ingest({url:'http://suno.com'}).accepted,'insecure source URL');
const accepted=ingest({});
ck(accepted.accepted===true&&accepted.integrityVerified===true,'local integrity pass');
ck(accepted.independentHostAttestation===false&&accepted.hostGateClosed===false,'local hash not host proof');
ck(accepted.evidence.sourceComplete===false,'no productive analytics promotion');
ck(!ingestSunoMonitorResult({...task,result:{...result,recorded_status:'failed'},currentHead:H,sourceRevision:H,reviewedSources:[proof]}).accepted,'failed run blocks');
const native=correct('Analytics Lübber ist die Dirigentin',defaultState());
ck(native.text.includes('LYVRA'),'original dictation still imports');
const evidence=ingestAnalyticsEvidence({kind:'SUNO_MONITOR',sourceId:'fixture',sourceRevision:H,observedAt:time,contentDigest:sha,assertion:'fixture'});
ck(evidence.independentHostVerification===false,'original evidence class not host proof');
const sourceBlobs=Object.fromEntries(ledger.carrierReadbacks.map(r=>[r.carrier,r.blob_sha]));
const contract='ROOT_AUTHORITY=WHOLE_LYVRA\nCURRENT_PLACEMENT=CENTRAL_SHARED_NATIVE_LYVRA_FACET\nANALYTICS_NE_TRACK_DESIGN_CHILD_FACET=true';
const args={currentHead:H,pointerBlob:P,contractText:contract,state:{facet_id:'LYVRA_ANALYTICS',root_authority:'WHOLE_LYVRA'},sourceBlobs,carrierReadbacks:ledger.carrierReadbacks};
const checked=assessAnalyticsMigration(args);
ck(checked.reviewedCarrierCount===6&&checked.missing.length===1,'six real native source carriers');
ck(checked.missing[0]==='CROSS_FACET_CALLERS','missing cross facet callers');
ck(!checked.candidateReadyForGovernedWriteReview&&!checked.productiveMigrationApplied,'no premature parentage change');
const spoof=assessAnalyticsMigration({...args,carrierReadbacks:[]});
ck(spoof.reviewedCarrierCount===0&&spoof.unverifiedShaClaims.length===6,'SHA-shaped assertions not enough');
ck(checked.openHostGates===18,'all 18 host gates remain open');
console.log(JSON.stringify({status:'PASS',checks:n,scope:'R41_ORIGINAL_SOURCE_REGRESSION_NOT_HOST',t07:'INTEGRITY_GATED_NO_HOST',t19:'SIX_OF_SEVEN_BLOCKED',write:false}));
