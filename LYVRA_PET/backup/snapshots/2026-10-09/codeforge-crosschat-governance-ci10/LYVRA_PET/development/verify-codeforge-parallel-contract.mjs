import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const c=JSON.parse(await readFile(new URL('./CODEFORGE_PARALLEL_GOVERNANCE_CONTRACT.json',import.meta.url),'utf8'));
assert.equal(c.status,'PROPOSAL_ONLY_NOT_CODEFORGE_ADOPTED');
assert.equal(c.principal_branch,'lyvra');
assert.equal(c.workspace_policy.cross_chat_last_writer_wins,false);
assert.equal(c.workspace_policy.concurrent_independent_branches,true);
for(const v of ['CODING_ASSISTANT','CODE_QUALITY','TESTING_AND_REPAIR','GITHUB_ACTIONS','BUILD_DEPLOY_READBACK'])assert.ok(c.core_mission.includes(v));
for(const v of ['OBSERVED','INFERRED','VERIFIED','DISPUTED','UNKNOWN'])assert.ok(c.evidence_states.includes(v));
const steps=c.promotion_sequence;
const before=(a,b)=>assert.ok(steps.indexOf(a)>=0&&steps.indexOf(b)>steps.indexOf(a),a+' must precede '+b);
before('BACKUP_VERIFIED','APPROVED_MAIN_MERGE');
before('FRESH_MAIN_HEAD','INTEGRATION_CANDIDATE');
before('CI_SECURITY_PLUGIN_LIVECIRCLE_REHYDRATION_CHECKS','APPROVED_MAIN_MERGE');
before('APPROVED_MAIN_MERGE','MERGE_READBACK');
before('MERGE_READBACK','CURRENT_POINTER_LAST');
before('RECOVERY_REFERENCE_VALIDATED','SAFE_BRANCH_CLEANUP');
for(const v of ['NO_FORCE_PUSH','NO_DELETE_ACTIVE_BRANCH','NO_AUTO_PRODUCTION_DEPLOY','NO_MERGE_ON_FAILED_TEST','NO_FOREIGN_MUTATION'])assert.ok(c.hardlocks.includes(v));
assert.equal(c.implementation.codeforge_native,'NOT_VERIFIED');
console.log('PASS CODEFORGE proposal: original coding mission, scoped cross-chat workspaces, evidence, promotion ordering, safe cleanup and authority boundaries');
