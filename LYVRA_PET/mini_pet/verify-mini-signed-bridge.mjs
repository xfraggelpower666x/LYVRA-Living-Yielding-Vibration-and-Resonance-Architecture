import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
import {createSignedEventProducer} from '../bridge/signed-event-transport.mjs';
import {createVerifiedMiniBridge} from './verified-mini-bridge.mjs';
const now=Date.parse('2026-10-09T17:00:00Z'),revision='a'.repeat(40);
const keys=await webcrypto.subtle.generateKey('Ed25519',true,['sign','verify']);
const producer=createSignedEventProducer({privateKey:keys.privateKey,keyId:'test-only',verifyNativeEvent:async()=>true,cryptoApi:webcrypto,clock:()=>now});
const mk=(kind='music_work')=>({pet_id:'pet_6ab791129364819183885f44a21497a2',authority:'WHOLE_LYVRA',source_revision:revision,evidence_id:'test-1',observed_at:new Date(now-1000).toISOString(),kind,facet:'track_design'});
const env=await producer.produce(mk());
const bridge=createVerifiedMiniBridge({trustedKeys:{'test-only':keys.publicKey},getParentRevision:async()=>revision,clock:()=>now,cryptoApi:webcrypto});
assert.equal((await bridge.accept(env)).mode,'ACTIVE');
assert.equal((await bridge.accept(env)).verified,false,'replay must fail closed');
bridge.reset();
assert.equal((await bridge.accept({...env,signature:'AAAA'})).verified,false,'forgery rejected');
const wrong= createVerifiedMiniBridge({trustedKeys:{'test-only':keys.publicKey},getParentRevision:async()=> 'b'.repeat(40),clock:()=>now,cryptoApi:webcrypto});
assert.equal((await wrong.accept(env)).verified,false,'wrong parent revision rejected');
bridge.reset();
assert.equal((await bridge.accept(env)).verified,true);
const second=await producer.produce({...mk('shared_success'),evidence_id:'test-2',observed_at:new Date(now-500).toISOString()});
assert.equal((await bridge.accept(second)).mode,'SUCCESS');
assert.equal((await bridge.accept(env)).verified,false,'older signed event rejected');
assert.equal((await bridge.accept(second)).verified,false,'repeated signed event rejected');
bridge.dispose();
assert.equal((await bridge.accept(env)).verified,false);
console.log('PASS mini signed Ed25519 verification, current revision, replay protection, reset and dispose');
