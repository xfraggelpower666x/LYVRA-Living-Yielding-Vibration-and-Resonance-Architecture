import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const base=new URL('./',import.meta.url);
const contract=await readFile(new URL('MINI_PET_FACET_CONTRACT.md',base),'utf8');
const cycle=JSON.parse(await readFile(new URL('livecircle/SUB_LIVECIRCLE_CURRENT.json',base),'utf8'));
const rehydrate=JSON.parse(await readFile(new URL('rehydration/SUB_REHYDRATION_MANIFEST.json',base),'utf8'));
assert.equal(cycle.authority,'LYVRA_PET/');
assert.equal(rehydrate.authority,'LYVRA_PET/');
assert.equal(cycle.pet_identity,'SAME_AS_PARENT_PET');
assert.equal(cycle.parent,'WHOLE_LYVRA');
assert.equal(cycle.live_approved,false,'Not yet released to chat hosts');
assert.equal(rehydrate.deployment,'NONE');
assert.equal(rehydrate.host_embedding_verified,false);
assert.equal(rehydrate.pointer_promotion,'BLOCKED_UNTIL_VERIFIED');
assert.equal(cycle.status,'DEVELOPMENT_CANDIDATE');
assert.equal(rehydrate.status,'DEV_ONLY_NOT_LIVE');
assert.ok(cycle.guards.includes('NO_SECOND_IDENTITY'));
assert.ok(cycle.guards.includes('NO_SECOND_MEMORY_ROOT'));
assert.ok(cycle.guards.includes('FREE_ONLY'));
assert.ok(cycle.guards.includes('SHARED_GITHUB_BUDGET'));
assert.ok(cycle.phases.includes('evidence_validation'));
assert.ok(cycle.phases.includes('expiry_reset'));
assert.ok(rehydrate.order.indexOf('rehydrate_whole_lyvra_current')<rehydrate.order.indexOf('rehydrate_parent_pet_current'));
assert.ok(rehydrate.order.indexOf('rehydrate_parent_pet_current')<rehydrate.order.indexOf('read_mini_facet_contract'));
for(const ref of rehydrate.artifacts)assert.ok(ref.startsWith('LYVRA_PET/mini_pet/'));
for(const phrase of ['no live chat embedding claimed','no second PET','max 300 REST calls','host-supported'])assert.ok(contract.includes(phrase),phrase);
console.log('PASS mini PET same-identity contract, independent lifecycle, parent-first rehydration, free-only safeguards and no premature release');
